    /**
     * Считает уровень по массиву ответов (индексы от 0).
     * Возвращает ['level' => float, 'score' => int, 'category' => string, 'valid' => bool].
     */
    public function evaluate(array $answers): array
    {
        $qs = self::questions();
        if (count($answers) !== count($qs)) {
            return ['valid' => false, 'error' => 'Нужно ответить на все 5 вопросов'];
        }

        $score = 0;
        foreach ($qs as $i => $q) {
            $ans = $answers[$i] ?? null;
            if (!is_int($ans) && !(is_string($ans) && ctype_digit($ans))) {
                return ['valid' => false, 'error' => 'Неверный формат ответа #' . ($i + 1)];
            }
            $ans = (int) $ans;
            $maxIdx = count($q['options']) - 1;
            if ($ans < 0 || $ans > $maxIdx) {
                return ['valid' => false, 'error' => 'Недопустимый вариант в вопросе #' . ($i + 1)];
            }
            $score += $ans;
        }

        $ratio = self::MAX_SCORE > 0 ? $score / self::MAX_SCORE : 0;
        $raw = self::MIN_LEVEL + $ratio * (self::MAX_LEVEL_FROM_QUIZ - self::MIN_LEVEL);
        // Округляем до 0.25
        $level = round($raw * 4) / 4;
        if ($level < self::MIN_LEVEL) $level = self::MIN_LEVEL;
        if ($level > self::MAX_LEVEL_FROM_QUIZ) $level = self::MAX_LEVEL_FROM_QUIZ;

        return [
            'valid' => true,
            'score' => $score,
            'max_score' => self::MAX_SCORE,
            'level' => $level,
            'category' => self::categoryFor($level),
        ];
    }

    public static function categoryFor(float $level): string
    {
        if ($level < 1.5) return 'Начинающий';
        if ($level < 2.5) return 'Ниже среднего';
        if ($level < 3.5) return 'Средний';
        if ($level < 4.5) return 'Выше среднего';
        return 'Продвинутый';
    }
}
