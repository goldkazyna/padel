<?php

namespace App\Support;

/**
 * Расписания «каждый с каждым в паре» для Американо и Round Robin.
 *
 * Раньше эти таблицы лежали копиями в двух сервисах, и копии разъезжались:
 * в одну добавляли размер, в другую забывали. Теперь источник один.
 *
 * Свойство расписаний: напарник не повторяется ни разу, соперник —
 * не больше двух раз, причём и если турнир закончить раньше срока.
 */
class PairingSchedules
{
    /**
     * Расписание для числа игроков или null, если готового нет
     * (тогда сервис считает сам).
     *
     * @return array<int, array<int, array<int, array<int, int>>>>|null
     */
