    {
        $schedules = [
        // 8 игроков — проверено ✅
        8 => [
            1 => [[[0,1], [2,3]], [[4,5], [6,7]]],
            2 => [[[0,2], [4,6]], [[1,3], [5,7]]],
            3 => [[[0,3], [5,6]], [[1,2], [4,7]]],
            4 => [[[0,4], [1,5]], [[2,6], [3,7]]],
            5 => [[[0,5], [2,7]], [[1,4], [3,6]]],
            6 => [[[0,6], [1,7]], [[2,4], [3,5]]],
            7 => [[[0,7], [3,4]], [[1,6], [2,5]]],
        ],
        
        // 12 игроков — проверено ✅ (с devenezia.com)
        12 => [
            1  => [[[11,0], [8,9]],   [[1,7], [2,5]],   [[3,10], [4,6]]],
            2  => [[[11,1], [9,10]],  [[2,8], [3,6]],   [[4,0], [5,7]]],
            3  => [[[11,2], [10,0]],  [[3,9], [4,7]],   [[5,1], [6,8]]],
            4  => [[[11,3], [0,1]],   [[4,10], [5,8]],  [[6,2], [7,9]]],
            5  => [[[11,4], [1,2]],   [[5,0], [6,9]],   [[7,3], [8,10]]],
            6  => [[[11,5], [2,3]],   [[6,1], [7,10]],  [[8,4], [9,0]]],
            7  => [[[11,6], [3,4]],   [[7,2], [8,0]],   [[9,5], [10,1]]],
            8  => [[[11,7], [4,5]],   [[8,3], [9,1]],   [[10,6], [0,2]]],
            9  => [[[11,8], [5,6]],   [[9,4], [10,2]],  [[0,7], [1,3]]],
            10 => [[[11,9], [6,7]],   [[10,5], [0,3]],  [[1,8], [2,4]]],
            11 => [[[11,10], [7,8]],  [[0,6], [1,4]],   [[2,9], [3,5]]],
        ],

        // 16 игроков — «вист-расписание»: за 15 раундов каждый играет
        // с каждым в паре ровно один раз и против каждого ровно дважды.
        // Больше двух встреч с одним соперником не будет и если
        // остановиться раньше — свойство держится на любом раунде.
        16 => [
            1  => [[[15,10], [12,4]],  [[2,8], [7,11]],  [[14,13], [9,6]],  [[1,3], [0,5]]],
            2  => [[[15,11], [13,5]],  [[3,9], [8,12]],  [[0,14], [10,7]],  [[2,4], [1,6]]],
            3  => [[[15,12], [14,6]],  [[4,10], [9,13]],  [[1,0], [11,8]],  [[3,5], [2,7]]],
            4  => [[[15,13], [0,7]],  [[5,11], [10,14]],  [[2,1], [12,9]],  [[4,6], [3,8]]],
            5  => [[[15,14], [1,8]],  [[6,12], [11,0]],  [[3,2], [13,10]],  [[5,7], [4,9]]],
