            7  => [[[15,1], [3,10]],  [[8,14], [13,2]],  [[5,4], [0,12]],  [[7,9], [6,11]]],
            8  => [[[15,2], [4,11]],  [[9,0], [14,3]],  [[6,5], [1,13]],  [[8,10], [7,12]]],
