{{-- Инструкция: Управление турниром (уведомления, правки, результаты). Скрины: public/help/manage-tournament/ --}}

<div class="ha-note">
    <div class="ic">i</div>
    <div>Здесь собраны действия «по ходу»: как позвать игроков пушем, поправить счёт, отменить турнир и посмотреть итоги.</div>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">1</div><h2 class="ha-step-t">Уведомить игроков (пуш)</h2></div>
    <p>В списке турниров у турнира со статусом <b>«Открыта регистрация»</b> есть кнопка-<b>колокольчик</b>. Нажмите — подходящим игрокам придёт пуш-уведомление в приложении о наборе.</p>
    <div class="ha-shot"><img src="{{ asset('help/manage-tournament/push-list.png') }}" alt="Кнопка пуш-уведомления в списке турниров"></div>
    <div class="ha-cap">Колокольчик показывается только для открытых турниров. Рядом — «глаз» (открыть) и «карандаш» (редактировать).</div>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">2</div><h2 class="ha-step-t">Поправить счёт по ходу</h2></div>
    <p>У сыгранного матча есть кнопка-<b>карандаш</b>. Нажмите — откроется окно <b>«Редактировать счёт»</b> с текущими цифрами. Измените и нажмите <span class="ha-kbd">Обновить</span> — таблица пересчитается.</p>
    <div class="ha-shot"><img src="{{ asset('help/manage-tournament/edit-score.png') }}" alt="Редактирование счёта матча"></div>
    <div class="ha-cap">Пока турнир не завершён, счёт любого матча можно переписать.</div>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">3</div><h2 class="ha-step-t">Отменить турнир</h2></div>
    <p>В шапке турнира — кнопка <span class="ha-kbd">Отменить</span> (красная). Она отменяет турнир целиком; система переспросит подтверждение.</p>
    <div class="ha-shot"><img src="{{ asset('help/manage-tournament/manage-header.png') }}" alt="Кнопки управления турниром в шапке"></div>
    <ul class="ha-list">
        <li>Рядом — <b>Сгенерировать раунд</b>, <b>Завершить турнир</b>, <b>Редактировать</b>.</li>
        <li>Отмена необратима — используйте, если турнир не состоится.</li>
        <li><b>Перезапуск</b> турнира в веб-панели не предусмотрен (только отмена).</li>
    </ul>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">4</div><h2 class="ha-step-t">Посмотреть результаты</h2></div>
    <p>У завершённого турнира (статус <b>«Завершён»</b>) на его странице видны итоги: таблица с местами, счёт матчей и — для командного — победитель.</p>
    <div class="ha-shot"><img src="{{ asset('help/manage-tournament/results.png') }}" alt="Результаты завершённого турнира"></div>
    <div class="ha-cap">Кнопки ввода счёта при этом отключены — турнир только для просмотра. Рейтинг уже применён.</div>
</div>
