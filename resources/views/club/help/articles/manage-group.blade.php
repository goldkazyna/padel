{{-- Инструкция: Группа — создание и участники. Скрины: public/help/manage-group/ --}}

<div class="ha-note">
    <div class="ic">i</div>
    <div><b>Группа</b> — это постоянный состав учеников с общим тренером и ценой занятия. Участники покупают <b>пакет занятий</b> (абонемент), который списывается при проведении.</div>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">1</div><h2 class="ha-step-t">Создайте группу</h2></div>
    <p>В разделе <span class="ha-kbd">Группы</span> нажмите <span class="ha-kbd">+ Создать группу</span> и заполните данные.</p>
    <div class="ha-shot"><img src="{{ asset('help/manage-group/create.png') }}" alt="Создание группы"></div>
    <ul class="ha-list">
        <li><b>Название</b> — обязательно (например «Утренняя»).</li>
        <li><b>Тренер</b> — кто ведёт (можно без тренера).</li>
        <li><b>Цена занятия для клиента</b> и <b>Макс. участников</b> — по желанию.</li>
        <li><b>Заметка</b> — любая доп. информация.</li>
    </ul>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">2</div><h2 class="ha-step-t">Добавьте участника с абонементом</h2></div>
    <p>Откройте группу и нажмите <span class="ha-kbd">+ Добавить</span> в блоке «Участники и остаток пакета».</p>
    <div class="ha-shot"><img src="{{ asset('help/manage-group/add-member.png') }}" alt="Добавление участника"></div>
    <ul class="ha-list">
        <li><b>Клиент</b> — найдите по имени или телефону (клиент должен быть в базе).</li>
        <li><b>Занятий в пакете</b> и <b>Сумма</b> — сколько купил и за сколько.</li>
        <li><b>Дата окончания абонемента</b> — по желанию.</li>
        <li><b>Способ оплаты</b> + галочка <b>Оплачено</b>.</li>
    </ul>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">3</div><h2 class="ha-step-t">Управляйте участниками</h2></div>
    <p>На странице группы у каждого участника виден <b>остаток пакета</b> и кнопки действий.</p>
    <div class="ha-shot"><img src="{{ asset('help/manage-group/detail.png') }}" alt="Страница группы"></div>
    <ul class="ha-list">
        <li>Тег <b>«N занятий»</b> — сколько осталось (зелёный — много, жёлтый — 1–2, красный — закончились).</li>
        <li><b>❄ Заморозка</b> — приостановить абонемент на период (продлевает срок).</li>
        <li><b>+</b> — добавить ещё пакет занятий (продление).</li>
        <li><b>✎ / ✕</b> — изменить или убрать участника из группы.</li>
    </ul>
    <div class="ha-cap">Кому пора продлевать — видно на странице <b>«Остатки»</b> (кнопка в списке групп).</div>
</div>
