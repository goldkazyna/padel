{{-- Инструкция: Расписание и брони кортов. Скрины: public/help/schedule-bookings/ --}}

<div class="ha-note">
    <div class="ic">i</div>
    <div>Раздел <b>Корты</b> — это расписание бронирований. Здесь видно занятость кортов и оформляются брони: разовые, групповые занятия и турниры.</div>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">1</div><h2 class="ha-step-t">Откройте расписание</h2></div>
    <p>Сетка <b>время × корты</b>. Сверху выбирается дата и день недели, справа — переключатель <span class="ha-kbd">По кортам</span> / <span class="ha-kbd">По дням</span>.</p>
    <div class="ha-shot"><img src="{{ asset('help/schedule-bookings/daily.png') }}" alt="Расписание кортов — по кортам"></div>
    <ul class="ha-list">
        <li>Цвет слота: зелёный — свободен, синий — оплачено, оранжевый — не оплачено, красный — не обработан, серый — заблокирован.</li>
        <li>В свободном слоте показана цена часа.</li>
    </ul>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">2</div><h2 class="ha-step-t">Создайте бронь</h2></div>
    <p>Нажмите на свободный слот — откроется окно <b>«Бронирование»</b>. Заполните данные и сохраните.</p>
    <div class="ha-shot"><img src="{{ asset('help/schedule-bookings/book.png') }}" alt="Окно бронирования"></div>
    <ul class="ha-list">
        <li><b>Длительность</b> — от 1 до 6 часов; цена и <b>Итого</b> считаются автоматически, можно задать <b>скидку</b>.</li>
        <li><b>Имя и телефон клиента</b> — обязательны; заметка — по желанию.</li>
        <li><b>Тип брони</b> — мягкая бронь, групповые, индивидуальные, турнир.</li>
        <li><b>Способ оплаты</b> (в т.ч. клубной картой) и <b>статус оплаты</b> (оплачено / не оплачено).</li>
        <li><b>Тренер</b> — можно добавить с оплатой за занятие.</li>
    </ul>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">3</div><h2 class="ha-step-t">Недельный вид и работа с бронями</h2></div>
    <p>Переключатель <span class="ha-kbd">По дням</span> показывает всю неделю сразу. Существующие брони видны цветными плашками.</p>
    <div class="ha-shot"><img src="{{ asset('help/schedule-bookings/week.png') }}" alt="Расписание кортов — по дням (неделя)"></div>
    <ul class="ha-list">
        <li>Клик по брони открывает её карточку — можно изменить, отметить оплату или <b>отменить</b>.</li>
        <li>Групповые занятия и турниры тоже отображаются в расписании (со своим цветом и подписью).</li>
    </ul>
</div>
