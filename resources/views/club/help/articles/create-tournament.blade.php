{{-- Инструкция: Как создать турнир. Скрины: public/help/create-tournament/ --}}

<div class="ha-note">
    <div class="ic">i</div>
    <div>Поля со звёздочкой <b style="color:#22c55e">*</b> обязательны. Пока статус — <b>Черновик</b>, игроки турнир не видят; настройки можно менять до старта.</div>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">1</div><h2 class="ha-step-t">Откройте раздел «Турниры клуба»</h2></div>
    <p>В левом меню выберите <span class="ha-kbd">Турниры клуба</span> и нажмите <span class="ha-kbd">+ Создать турнир</span> в правом верхнем углу.</p>
    <div class="ha-shot"><img src="{{ asset('help/create-tournament/01-list.png') }}" alt="Список турниров клуба"></div>
    <div class="ha-cap">Здесь же видно все турниры со статусами: «Открыта регистрация», «Идёт турнир», «Завершён».</div>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">2</div><h2 class="ha-step-t">Заполните основные поля</h2></div>
    <p>Сначала выберите <b>Тип турнира</b> — от него зависят настройки ниже. Затем заполните название, дату и параметры участников.</p>
    <div class="ha-shot"><img src="{{ asset('help/create-tournament/02-form.png') }}" alt="Форма создания турнира"></div>
    <ul class="ha-list">
        <li><b>Тип турнира</b> — Американо, Мексикано, Командный, King of Court, Americano Flex, Round Robin и др.</li>
        <li><b>Название</b> и <b>Описание</b> — что увидят игроки в приложении.</li>
        <li><b>Клуб (площадка)</b> — необязательно; где физически играют.</li>
        <li><b>Дата и время</b>, <b>Длительность</b> — когда и на сколько.</li>
        <li><b>Мин. / Макс. уровень</b> — диапазон допуска. Игроки вне диапазона записаться не смогут.</li>
        <li><b>Макс. участников</b> и <b>Стоимость</b> — размер турнира и цена входа.</li>
        <li><b>Забронировать мест</b> — резерв под своих (не займут игроки из приложения).</li>
        <li><b>Лист ожидания</b> — сколько человек встанут в очередь, когда мест не останется.</li>
    </ul>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">3</div><h2 class="ha-step-t">Настройте формат и участие</h2></div>
    <p>Ниже в той же форме — блок, зависящий от выбранного типа, и общие переключатели.</p>
    <ul class="ha-list">
        <li><b>Названия кортов</b> — можно задать свои; пусто = «Корт 1», «Корт 2»…</li>
        <li><b>Рейтинговый турнир</b> — результаты повлияют на рейтинг игроков (по умолчанию включено).</li>
        <li><b>Только для верифицированных</b> — заявки только от игроков с аватаром и хотя бы одним сыгранным турниром.</li>
        <li><b>Количество групп / раундов</b> — для Американо; раунды считаются автоматически, можно поправить.</li>
        <li><b>Плей-офф</b> — включите, чтобы добавить стадию навылет после группового этапа.</li>
    </ul>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">4</div><h2 class="ha-step-t">Выберите статус и сохраните</h2></div>
    <p>Внизу формы — поле <b>Статус</b> и кнопка <span class="ha-kbd">Создать</span>.</p>
    <ul class="ha-list">
        <li><b>Черновик</b> — турнир сохранится, но игроки его не видят. Удобно подготовить заранее.</li>
        <li><b>Открыт</b> — сразу появляется в приложении, начинается запись.</li>
    </ul>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">5</div><h2 class="ha-step-t">Что дальше</h2></div>
    <p>После сохранения открывается карточка турнира — там идёт вся работа.</p>
    <ul class="ha-list">
        <li>Добавляйте участников вручную или ждите записи из приложения; заявки подтверждаются в модерации.</li>
        <li>Когда набралось нужное число — <b>«Начать турнир»</b> (для командного сначала распределение по группам).</li>
        <li>По ходу вносите счёт по раундам; в конце — <b>«Завершить»</b>, и рейтинг применится автоматически.</li>
    </ul>
</div>
