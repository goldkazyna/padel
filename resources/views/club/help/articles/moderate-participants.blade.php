{{-- Инструкция: Модерация и добавление участников. Скрин: public/help/moderate-participants/ --}}

<div class="ha-note">
    <div class="ic">i</div>
    <div>Когда игрок записывается из приложения, его заявка может попасть <b>на модерацию</b> — вы решаете, принять или отклонить. Здесь же можно добавить игрока вручную или пригласить.</div>
</div>

<div class="ha-shot"><img src="{{ asset('help/moderate-participants/moderation.png') }}" alt="Модерация заявок на турнир"></div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">1</div><h2 class="ha-step-t">Разберите заявки на модерации</h2></div>
    <p>Блок <b>«Заявки на модерации»</b> вверху списка — это игроки, ждущие решения. У каждой заявки видно имя, телефон, уровень и рейтинг.</p>
    <ul class="ha-list">
        <li>Зелёная <b>✓</b> — принять заявку (игрок станет участником).</li>
        <li>Красная <b>✕</b> — отклонить.</li>
        <li>Кнопка <span class="ha-kbd">Одобрить все</span> — принять сразу все заявки.</li>
    </ul>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">2</div><h2 class="ha-step-t">Добавьте или пригласите игрока</h2></div>
    <p>Ниже списка есть два поля:</p>
    <ul class="ha-list">
        <li><b>Добавить участника</b> — впишите телефон или имя и нажмите «Добавить». Игрок сразу попадёт в список (без заявки).</li>
        <li><b>Приглашения</b> — отправьте игроку приглашение: ему придёт пуш, и он сможет записаться сам.</li>
    </ul>
</div>

<div class="ha-step">
    <div class="ha-step-h"><div class="ha-step-n">3</div><h2 class="ha-step-t">Когда все одобрены — к старту</h2></div>
    <p>Пока не одобрены все участники, группы сформировать нельзя (внизу подсказка «Одобрено N из M»). Как только состав утверждён — жмите <span class="ha-kbd">Сформировать группы</span> и запускайте турнир (см. «Как проводить Американо»).</p>
    <div class="ha-cap">Одобренные участники отмечены галочкой и подписью «Одобрен»; у каждого можно поправить данные или убрать из турнира.</div>
</div>
